function renderMasonryGrid(gridId, items) {
    const grid = document.getElementById(gridId);
    if (!grid) return;

    items.forEach(function(item, index) {
        var div = document.createElement("div");
        div.className = "masonry-item";

        var imgEl = document.createElement("img");
        imgEl.src = item.path;
        imgEl.alt = item.title;
        imgEl.loading = "lazy";
        imgEl.decoding = "async";

        var overlay = document.createElement("div");
        overlay.className = "masonry-overlay";

        var viewBtn = document.createElement("div");
        viewBtn.className = "view-btn";
        viewBtn.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M2 12s3-7 10-7 10 7 10 7-3 7-10 7-10-7-10-7Z"></path><circle cx="12" cy="12" r="3"></circle></svg> View';
        overlay.appendChild(viewBtn);

        if (item.url) {
            var link = document.createElement("a");
            link.href = item.url;
            link.target = "_blank";
            link.rel = "noopener noreferrer";
            link.appendChild(imgEl);
            link.appendChild(overlay);
            div.appendChild(link);
        } else {
            div.appendChild(imgEl);
            div.appendChild(overlay);
        }

        grid.appendChild(div);
    });
}

document.addEventListener("DOMContentLoaded", function() {

    var totalImages = document.querySelectorAll("img").length;
    var loadedImages = 0;
    var loader = document.getElementById("page-loader");

    function checkAllLoaded() {
        loadedImages++;
        if (loadedImages >= totalImages) {
            dismissLoader();
        }
    }

    function dismissLoader() {
        if (loader) {
            loader.classList.add("hidden");
        }
        document.body.classList.remove("no-scroll");
        if (typeof lenis !== 'undefined' && lenis) {
            lenis.start();
        }
        ScrollTrigger.refresh();
    }

    document.querySelectorAll("img").forEach(function(img) {
        if (img.complete) {
            checkAllLoaded();
        } else {
            img.addEventListener("load", checkAllLoaded);
            img.addEventListener("error", checkAllLoaded);
        }
    });

    setTimeout(dismissLoader, 8000);

    var lenis = new Lenis({
        duration: 1.2,
        easing: function(t) { return Math.min(1, 1.001 - Math.pow(2, -10 * t)); },
        direction: "vertical",
        gestureDirection: "vertical",
        smooth: true,
        mouseMultiplier: 1,
        smoothTouch: false,
        touchMultiplier: 2,
        infinite: false
    });
    lenis.stop();

    function raf(time) {
        lenis.raf(time);
        requestAnimationFrame(raf);
    }
    requestAnimationFrame(raf);

    gsap.registerPlugin(ScrollTrigger);

    lenis.on("scroll", ScrollTrigger.update);
    gsap.ticker.add(function(time) {
        lenis.raf(time * 1000);
    });
    gsap.ticker.lagSmoothing(0);

    var roles = ["Digital Marketer", "Content Creator", "Web Developer", "Social Media Manager"];
    var roleIndex = 0;
    var charIndex = 0;
    var isDeleting = false;
    var typewriterElement = document.getElementById("typewriter");

    function type() {
        var currentRole = roles[roleIndex];

        if (isDeleting) {
            typewriterElement.textContent = currentRole.substring(0, charIndex - 1);
            charIndex--;
        } else {
            typewriterElement.textContent = currentRole.substring(0, charIndex + 1);
            charIndex++;
        }

        var typeSpeed = isDeleting ? 50 : 100;

        if (!isDeleting && charIndex === currentRole.length) {
            typeSpeed = 2000;
            isDeleting = true;
        } else if (isDeleting && charIndex === 0) {
            isDeleting = false;
            roleIndex = (roleIndex + 1) % roles.length;
            typeSpeed = 500;
        }

        setTimeout(type, typeSpeed);
    }

    type();

    var aboutContainer = document.getElementById("about-container");
    var aboutHeader = document.getElementById("about-header");

    if (aboutContainer && aboutHeader) {
        var tl = gsap.timeline({
            scrollTrigger: {
                trigger: aboutContainer,
                start: "top bottom",
                end: "bottom top",
                scrub: 1.5
            }
        });

        tl.fromTo(aboutHeader,
            { y: 50, scale: 0.9 },
            { y: -120, scale: 1.1, duration: 1, ease: "none" }
        , 0);
    }

    renderMasonryGrid("grid-video", portfolioData.video);
    renderMasonryGrid("grid-madina", portfolioData.madina);
    renderMasonryGrid("grid-urang", portfolioData.urang);
    renderMasonryGrid("grid-web", portfolioData.web);
    renderMasonryGrid("grid-gallery", portfolioData.gallery);

    document.querySelectorAll('.reveal').forEach(function(el) {
        gsap.to(el, {
            scrollTrigger: {
                trigger: el,
                start: "top 90%",
                toggleActions: "play none none reverse",
            },
            opacity: 1,
            y: 0,
            scale: 1,
            filter: "blur(0px)",
            duration: 0.8,
            ease: "power2.out"
        });
    });

    document.querySelectorAll('.portfolio-category').forEach(function(cat) {
        var items = cat.querySelectorAll('.masonry-item');
        if (items.length > 0) {
            gsap.fromTo(items, 
                { opacity: 0, y: 50, scale: 0.9, filter: "blur(8px)" },
                {
                    scrollTrigger: {
                        trigger: cat,
                        start: "top 85%",
                        toggleActions: "play none none reverse"
                    },
                    opacity: 1,
                    y: 0,
                    scale: 1,
                    filter: "blur(0px)",
                    duration: 0.6,
                    stagger: 0.05,
                    ease: "back.out(1.2)"
                }
            );
        }
    });

    var timelineItems = document.querySelectorAll('.timeline-item');
    if (timelineItems.length > 0) {
        gsap.fromTo(timelineItems, 
            { opacity: 0, x: -30, filter: "blur(5px)" },
            {
                scrollTrigger: {
                    trigger: "#experience",
                    start: "top 80%",
                    toggleActions: "play none none reverse"
                },
                opacity: 1,
                x: 0,
                filter: "blur(0px)",
                duration: 0.8,
                stagger: 0.15,
                ease: "power2.out"
            }
        );
    }

    var orb = document.querySelector('.gradient-orb');
    if (orb) {
        gsap.to(orb, {
            scrollTrigger: {
                trigger: "body",
                start: "top top",
                end: "bottom bottom",
                scrub: 2
            },
            yPercent: 30,
            rotation: 45,
            ease: "none"
        });
    }

    var navItems = document.querySelectorAll(".nav-item");
    var sectionIds = [];
    navItems.forEach(function(item) {
        sectionIds.push(item.getAttribute("href"));
    });

    sectionIds.forEach(function(id) {
        var section = document.querySelector(id);
        if (section) {
            ScrollTrigger.create({
                trigger: section,
                start: "top center",
                end: "bottom center",
                onToggle: function(self) {
                    if (self.isActive) {
                        navItems.forEach(function(nav) { nav.classList.remove("active"); });
                        var activeNav = document.querySelector('.nav-item[href="' + id + '"]');
                        if (activeNav) activeNav.classList.add("active");
                    }
                }
            });
        }
    });

    document.querySelectorAll('a[href^="#"]').forEach(function(anchor) {
        anchor.addEventListener("click", function(e) {
            e.preventDefault();
            var targetId = this.getAttribute("href");
            if (targetId === "#") return;

            var target = document.querySelector(targetId);
            if (target) {
                lenis.scrollTo(target, { offset: 0, duration: 1.5 });
            }
        });
    });
});
